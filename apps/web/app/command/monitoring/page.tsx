"use client";

import { Suspense, useEffect, useMemo, useState } from "react";
import { useSearchParams } from "next/navigation";
import { useSession } from "@/lib/session";
import { useApi } from "@/lib/useApi";
import { api, ApiError } from "@/lib/api";
import {
  AlertBanner,
  Button,
  Card,
  CardHeader,
  ErrorState,
  LoadingRows,
  PageHeader,
  PermissionNotice,
  StatusBadge,
} from "@/components/ui";
import { formatCoordinates, formatDateTime } from "@/lib/format";
import type { Camera } from "@/lib/types";

interface LiveSession {
  session_id: string;
  status: string;
  is_simulated: boolean;
  mode?: string;
  detail?: string | null;
}

export default function MonitoringPage() {
  return (
    <Suspense fallback={<LoadingRows tone="command" label="Loading monitoring view…" />}>
      <MonitoringInner />
    </Suspense>
  );
}

function MonitoringInner() {
  const { has } = useSession();
  const params = useSearchParams();
  const cameras = useApi<Camera[]>("/api/v1/cameras?limit=100");
  const [selected, setSelected] = useState<string | null>(params.get("camera"));
  const [session, setSession] = useState<LiveSession | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [notice, setNotice] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const [elapsed, setElapsed] = useState(0);

  const camera = useMemo(
    () => (cameras.data ?? []).find((item) => item.id === selected) ?? null,
    [cameras.data, selected],
  );

  useEffect(() => {
    if (!session || session.status !== "active") return;
    const timer = setInterval(() => setElapsed((value) => value + 1), 1000);
    return () => clearInterval(timer);
  }, [session]);

  if (!has("camera:read")) return <PermissionNotice tone="command" permission="camera:read" />;

  async function start() {
    if (!selected) return;
    setBusy(true);
    setError(null);
    setNotice(null);
    try {
      const result = await api.post<LiveSession>(`/api/v1/cameras/${selected}/live/simulate`, {
        confirm: true,
      });
      setSession(result);
      setElapsed(0);
      cameras.reload();
    } catch (err) {
      setError(err instanceof ApiError ? err.message : "Could not start the simulated stream.");
    } finally {
      setBusy(false);
    }
  }

  async function stop() {
    if (!selected) return;
    setBusy(true);
    setError(null);
    try {
      await api.post(`/api/v1/cameras/${selected}/live/stop`);
      setSession(null);
      setNotice("Simulated stream stopped. A simulated session never implies a real camera feed.");
      cameras.reload();
    } catch (err) {
      setError(err instanceof ApiError ? err.message : "Could not stop the stream.");
    } finally {
      setBusy(false);
    }
  }

  return (
    <>
      <PageHeader
        title="Live monitoring"
        description="Simulated-live only. No real RTSP source is connected in this prototype, so the adapter reports its true state instead of pretending to stream."
        tone="command"
      />

      <AlertBanner kind="warn">
        <strong>SIMULATED LIVE</strong> — frames are generated by the demo generator. Nothing on
        this page is a real city feed.
      </AlertBanner>

      {error ? <AlertBanner kind="danger">{error}</AlertBanner> : null}
      {notice ? <AlertBanner kind="info">{notice}</AlertBanner> : null}

      <div className="grid gap-5 lg:grid-cols-3">
        <Card tone="command" className="lg:col-span-1">
          <CardHeader title="Camera sources" tone="command" />
          {cameras.loading ? (
            <LoadingRows tone="command" />
          ) : cameras.error ? (
            <ErrorState tone="command" message={cameras.error} onRetry={cameras.reload} />
          ) : (
            <ul className="divide-y divide-[var(--border-subtle)]">
              {(cameras.data ?? []).map((item) => {
                const isSelected = selected === item.id;
                return (
                  <li key={item.id}>
                    <button
                      type="button"
                      onClick={() => {
                        setSelected(item.id);
                        setSession(null);
                        setElapsed(0);
                      }}
                      className={`w-full px-4 py-3 text-left text-sm transition ${
                        isSelected
                          ? "bg-[var(--accent-soft)]"
                          : "hover:bg-[var(--bg-hover)]"
                      }`}
                    >
                      <span className="flex items-center justify-between gap-2">
                        <span className="font-mono text-xs font-semibold text-[var(--text-primary)]">
                          {item.camera_code}
                        </span>
                        <StatusBadge status={item.connection_status} />
                      </span>
                      <span className="mt-1 block text-xs text-[var(--text-secondary)]">
                        {item.name} · {item.source_type.replace(/_/g, " ")}
                      </span>
                    </button>
                  </li>
                );
              })}
            </ul>
          )}
        </Card>

        <div className="space-y-4 lg:col-span-2">
          <Card tone="command">
            <CardHeader
              title={camera ? `${camera.camera_code} — ${camera.name}` : "Select a camera"}
              description={
                camera
                  ? `${formatCoordinates(camera.location?.latitude, camera.location?.longitude)} · last seen ${formatDateTime(camera.last_seen_at)}`
                  : "Choose a source from the list to open the monitoring panel."
              }
              tone="command"
              actions={
                camera && has("camera:manage") ? (
                  session?.status === "active" ? (
                    <Button tone="command" variant="danger" onClick={() => void stop()} disabled={busy}>
                      Stop simulated stream
                    </Button>
                  ) : (
                    <Button tone="command" onClick={() => void start()} disabled={busy}>
                      Start simulated stream
                    </Button>
                  )
                ) : null
              }
            />
            <div className="px-5 py-4">
              <div className="surface-data relative flex aspect-video w-full items-center justify-center overflow-hidden rounded-[12px]">
                <div
                  className="absolute inset-0 opacity-25"
                  style={{
                    backgroundImage:
                      "linear-gradient(var(--border-subtle) 1px, transparent 1px), linear-gradient(90deg, var(--border-subtle) 1px, transparent 1px)",
                    backgroundSize: "32px 32px",
                  }}
                />
                <div className="relative px-4 text-center">
                  {session?.status === "active" ? (
                    <>
                      <p
                        className="flex items-center justify-center gap-2 text-sm font-semibold"
                        style={{ color: "var(--status-danger)" }}
                      >
                        <span
                          className="inline-block h-2 w-2 animate-pulse rounded-full"
                          style={{ backgroundColor: "var(--status-danger)" }}
                        />
                        SIMULATED LIVE · {String(Math.floor(elapsed / 60)).padStart(2, "0")}:
                        {String(elapsed % 60).padStart(2, "0")}
                      </p>
                      <p className="mt-2 max-w-md text-xs text-[var(--text-secondary)]">
                        Frame source: demo generator. Detection on live frames is not wired into
                        this panel; upload recorded footage to run the pipeline.
                      </p>
                    </>
                  ) : (
                    <>
                      <p className="text-sm font-medium text-[var(--text-primary)]">No active stream</p>
                      <p className="mt-1 max-w-md text-xs text-[var(--text-secondary)]">
                        Starting a simulated stream only changes the monitored state. It does not
                        connect to any real camera.
                      </p>
                    </>
                  )}
                </div>
              </div>
              <dl className="mt-4 grid gap-3 text-sm sm:grid-cols-3">
                <div>
                  <dt className="text-[11px] uppercase tracking-wide text-[var(--text-muted)]">Session</dt>
                  <dd className="mt-0.5 font-mono text-xs text-[var(--text-primary)]">
                    {session ? session.session_id.slice(0, 8) : "—"}
                  </dd>
                </div>
                <div>
                  <dt className="text-[11px] uppercase tracking-wide text-[var(--text-muted)]">State</dt>
                  <dd className="mt-0.5 text-[var(--text-primary)]">{session ? session.status : "idle"}</dd>
                </div>
                <div>
                  <dt className="text-[11px] uppercase tracking-wide text-[var(--text-muted)]">Mode</dt>
                  <dd className="mt-0.5 text-[var(--text-primary)]">{session?.mode ?? "not connected"}</dd>
                </div>
              </dl>
              {session?.detail ? (
                <p className="surface-data mt-3 rounded-[10px] px-3 py-2 text-xs text-[var(--text-secondary)]">
                  {session.detail}
                </p>
              ) : null}
            </div>
          </Card>

          <Card tone="command" variant="secondary">
            <CardHeader title="What this panel does not claim" tone="command" />
            <ul className="list-disc space-y-1.5 px-8 py-3.5 text-xs text-[var(--text-secondary)]">
              <li>No real RTSP connection is attempted; the adapter reports BLOCKED until credentials are configured.</li>
              <li>Frame-based speed is not estimated from pixels — there is no calibration record.</li>
              <li>Nothing detected on a simulated stream would count as an accident without human review.</li>
            </ul>
          </Card>
        </div>
      </div>
    </>
  );
}
